import assert from 'node:assert/strict';
import {buildKernTable, getKerningValue, normalizeKerningPairs} from '../src/kerning.js';

const pairs = [{left:'V',right:'A',value:-80},{left:'A',right:'V',value:-50}];
assert.deepEqual(normalizeKerningPairs(pairs), pairs);
assert.equal(getKerningValue(pairs,'A','V'),-50);
assert.equal(getKerningValue(pairs,'V','A'),-80);
assert.equal(getKerningValue(pairs,'A','A'),0);
assert.deepEqual(normalizeKerningPairs(undefined),[]);
assert.throws(()=>normalizeKerningPairs([{left:'AB',right:'A',value:-20}]),/некорректные символы/);
assert.throws(()=>normalizeKerningPairs([{left:'\\uD800',right:'A',value:-20}]),/некорректные символы/);
assert.throws(()=>normalizeKerningPairs([{left:'A',right:'V',value:1.5}]),/целым числом/);
assert.throws(()=>normalizeKerningPairs([{left:'A',right:'V',value:32768}]),/целым числом/);
assert.throws(()=>normalizeKerningPairs([{left:'A',right:'V',value:-20},{left:'A',right:'V',value:-30}]),/повторяется/);
const bytes=buildKernTable(pairs,{65:2,86:3});
assert.ok(Array.isArray(bytes));
const view=new DataView(Uint8Array.from(bytes).buffer);
assert.equal(view.getUint16(0),0);
assert.equal(view.getUint16(2),1);
assert.equal(view.getUint16(4),0);
assert.equal(view.getUint16(6),26);
assert.equal(view.getUint16(8),1);
assert.equal(view.getUint16(10),2);
assert.equal(view.getUint16(12),12);
assert.equal(view.getUint16(14),1);
assert.equal(view.getUint16(16),0);
assert.deepEqual([[view.getUint16(18),view.getUint16(20),view.getInt16(22)],[view.getUint16(24),view.getUint16(26),view.getInt16(28)]],[[2,3,-50],[3,2,-80]]);
assert.equal(buildKernTable([] ,{}),null);
assert.throws(()=>buildKernTable([{left:'A',right:'V',value:-50}],{65:2}),/нарисуйте и экспортируйте оба глифа/);
assert.throws(()=>buildKernTable([{left:'A',right:'V',value:-50}],{65:2,86:2}),/одной и той же паре глифов/);
console.log('GlyphFlow kerning tests passed: scalar validation, duplicate/range guards, deterministic format-0 binary, sorted glyph pairs and missing-cmap rejection.');
